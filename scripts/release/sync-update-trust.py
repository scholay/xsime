#!/usr/bin/env python3
"""Generate native public trust anchors; private signing keys never enter Git."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def generated(root=ROOT):
    registry = json.loads((root / "Shared/AppUpdate/trusted_keys.json").read_text())
    if registry.get("schemaVersion") != 1 or registry.get("algorithm") != "ecdsa-p256-sha256":
        raise ValueError("Unsupported update trust registry")
    keys = registry["keys"]
    if not 1 <= len(keys) <= 8 or len({key["id"] for key in keys}) != len(keys):
        raise ValueError("Expected unique, bounded trusted keys")
    for key in keys:
        if not re.fullmatch(r"[a-zA-Z0-9._-]{1,80}", key["id"]) or not re.fullmatch(r"04[0-9a-f]{128}", key["publicKey"]):
            raise ValueError("Expected key id and uncompressed P-256 public key")
    header = "// Generated by scripts/release/sync-update-trust.py. Public keys only.\n#pragma once\n#include <array>\n#include <string_view>\nnamespace rimes::updates {\nstruct TrustedUpdateKey { std::string_view id, public_key_hex; };\n"
    header += f"inline constexpr std::array<TrustedUpdateKey, {len(keys)}> kTrustedUpdateKeys = {{{{\n"
    header += "".join(f'    {{"{key["id"]}", "{key["publicKey"]}"}},\n' for key in keys)
    header += "}};\n} // namespace rimes::updates\n"
    swift = "// Generated by scripts/release/sync-update-trust.py. Public keys only.\nenum UpdateTrust {\n    static let keys: [String: String] = [\n"
    swift += "".join(f'        "{key["id"]}": "{key["publicKey"]}",\n' for key in keys)
    swift += "    ]\n}\n"
    java = "// Generated by scripts/release/sync-update-trust.py. Public keys only.\npackage org.scholay.rimes.android;\n\nfinal class UpdateTrust {\n    private UpdateTrust() { }\n    static String publicKeyFor(String id) {\n"
    java += "".join(f'        if ("{key["id"]}".equals(id)) return "{key["publicKey"]}";\n' for key in keys)
    java += "        return null;\n    }\n}\n"
    return {
        "Shared/AppUpdate/trusted_keys.generated.hpp": header,
        "Sources/RimeBuffer/UpdateTrust.generated.swift": swift,
        "platforms/android/app/src/main/java/org/scholay/rimes/android/UpdateTrust.java": java,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generated().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Update public key source is stale: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
